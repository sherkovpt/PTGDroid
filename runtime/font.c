void font_char(SDL_Renderer *r, char ch, int x, int y, int px) {
    ch = (char)toupper((unsigned char)ch);
    for (size_t g = 0; g < sizeof glyphs / sizeof glyphs[0]; g++) {
        if (glyphs[g].ch != ch) continue;
        for (int row = 0; row < 7; row++)
            for (int col = 0; col < 5; col++)
                if (glyphs[g].rows[row] & (0x10 >> col)) {
                    SDL_Rect p = { x + col * px, y + row * px, px, px };
                    SDL_RenderFillRect(r, &p);
                }
        return;
    }
}

int font_width(const char *s, int px) {
    int n = 0;
    while (s[n]) n++;
    return n ? (n * 6 - 1) * px : 0;
}

void font_text(SDL_Renderer *r, const char *s, int x, int y, int px) {
    for (; *s; s++, x += 6 * px) font_char(r, *s, x, y, px);
}

void font_text_centered(SDL_Renderer *r, const char *s, SDL_Rect box, int px) {
    font_text(r, s, box.x + (box.w - font_width(s, px)) / 2, box.y + (box.h - 7 * px) / 2, px);
}
